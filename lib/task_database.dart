class SponsorLink {
  final String type; // 'product', 'video', 'service'
  final String title;
  final String description;
  final String url;
  final String? imageUrl;

  SponsorLink({
    required this.type,
    required this.title,
    required this.description,
    required this.url,
    this.imageUrl,
  });
}

class Task {
